# Task 3: Importent NumPy Mathematical Formulas

import numpy as np

values = np.array([2, 4, 6, 8, 10])

square_root = np.sqrt(values)
exponential = np.exp(values)
logarithm = np.log(values)
sum_element = np.sum(values)
cumulative_sum = np.cumsum(values)

print("Square Root:", square_root)
print("Exponential:", exponential)
print("Logarithm:", logarithm)
print("Sum of elements:", sum_element)
print("Cumulative Sum:", cumulative_sum)
